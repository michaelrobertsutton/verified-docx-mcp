import fs from 'node:fs';
import {webcrypto} from 'node:crypto';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {DOMParser} from './shape_dom.mjs';
const sandbox={crypto:webcrypto,DOMParser,Office:{onReady(){}},document:{getElementById:()=>({addEventListener(){}})}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(process.argv[2],'utf8')+'\nglobalThis.api={explicitSegments,inlineLedger};',sandbox);
const {explicitSegments,inlineLedger}=sandbox.api;
const format={bold:false,italic:false,underline:'None',strikeThrough:false,doubleStrikeThrough:false,subscript:false,superscript:false,color:'#000000',name:'Calibri',size:11};
const segments=[{text:'Label:',format:{...format,bold:true}},{text:' plain',format}];
assert.equal(explicitSegments({replace:'Label: plain',replacement_segments:segments})[1].format.bold,false);
assert.throws(()=>explicitSegments({replace:'different',replacement_segments:segments}),e=>e.code==='INVALID_INPUT');
assert.throws(()=>explicitSegments({replace:'x',replacement_segments:[{text:'x',format:{bold:true}}]}),e=>e.code==='INVALID_INPUT');
assert.equal(explicitSegments({replace:'legacy'}),null);
const w='http://schemas.openxmlformats.org/wordprocessingml/2006/main';
const xml=`<w:document xmlns:w="${w}"><w:body><w:p><w:r><w:rPr><w:b/></w:rPr><w:t>α😀</w:t></w:r><w:r><w:t>: plain</w:t><w:br/><w:t>line</w:t></w:r></w:p></w:body></w:document>`;
const ledger=inlineLedger(xml);
assert.equal(ledger.map(c=>c.ch).join(''),'α😀: plain\vline');
assert.notEqual(ledger[0].format,ledger[2].format);
assert.equal(ledger[0].format,ledger[1].format);
assert.equal(inlineLedger(xml.replace('</w:body>','<w:p/></w:body>')).map(c=>c.ch).join(''),'α😀: plain\vline');
assert.throws(()=>inlineLedger(xml.replace('</w:body>','<w:p><w:r><w:t>Other paragraph</w:t></w:r></w:p></w:body>')),e=>e.code==='STRUCTURAL_BOUNDARY');
console.log('Explicit formatting and unchanged-character ledger passed');
