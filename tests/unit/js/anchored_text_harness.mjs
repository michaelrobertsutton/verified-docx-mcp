import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
import assert from 'node:assert/strict';
import {DOMParser,EMPTY} from './shape_dom.mjs';
const w='http://schemas.openxmlformats.org/wordprocessingml/2006/main', wp='http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing';
const drawing='<wp:anchor behindDoc="0"><wp:positionH relativeFrom="page"><wp:posOffset>25</wp:posOffset></wp:positionH><wp:extent cx="100" cy="200"/><wp:wrapSquare wrapText="bothSides"/><wp:docPr id="7" name="Callout"/></wp:anchor>';
let xml=`<w:document xmlns:w="${w}" xmlns:wp="${wp}"><w:body><w:p><w:r><w:t>Before</w:t>${drawing}<w:t>After</w:t></w:r></w:p></w:body></w:document>`;
const paragraph={getOoxml:()=>({value:xml})};
let targetXml=EMPTY;
const range={getOoxml:()=>({value:targetXml}),paragraphs:{items:[paragraph],load(){}}};
const sandbox={crypto:webcrypto,DOMParser,Office:{onReady(){}},document:{getElementById:()=>({addEventListener(){}})}};
vm.createContext(sandbox);vm.runInContext(fs.readFileSync(process.argv[2],'utf8')+'\nglobalThis.api={anchoredTextBoundary,verifyAnchoredText};',sandbox);
const ctx={sync:async()=>{}};
const before=await sandbox.api.anchoredTextBoundary(ctx,[range],{find:'Before',replace:'New'});
xml=xml.replace('Before','New');
await sandbox.api.verifyAnchoredText(ctx,before);
xml=xml.replace('cx="100"','cx="101"');
await assert.rejects(()=>sandbox.api.verifyAnchoredText(ctx,before),e=>e.code==='VERIFICATION_FAILED');
xml=xml.replace('cx="101"','cx="100"');targetXml=xml;
await assert.rejects(()=>sandbox.api.anchoredTextBoundary(ctx,[range],{find:'BeforeAfter',replace:'New'}),e=>e.code==='ANCHORED_SHAPES');
targetXml=EMPTY;
await assert.rejects(()=>sandbox.api.anchoredTextBoundary(ctx,[range],{find:'Before',replace:'New\nparagraph'}),e=>e.code==='ANCHORED_SHAPES');
console.log('Anchored text boundaries preserve definitions and refuse anchor writes');
